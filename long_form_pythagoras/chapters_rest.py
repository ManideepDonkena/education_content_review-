        self.cue('What remains is a squared plus b squared',self.panel_to(eq('a^2+b^2=c^2',49,PINK)))
        self.cue('We used arbitrary positive lengths',Circumscribe(self.panel,color=GOLD));self.finish()
        self.begin('20');self.cue('Notice what the proof depended on',tris.animate.set_fill(opacity=.22),self.panel_to(txt('Four congruent triangles',28)))
        self.cue('We justified the central square',Indicate(inner,color=PINK),self.panel_to(txt('The central shape is a square',26),eq(r'\text{area}=c^2',44,PINK)))
        self.cue('Then we counted the same region twice',Indicate(outer),self.panel_to(txt('Same region, two counts',28),eq('a^2+b^2=c^2',46)))
        self.cue('When you remember the formula',Indicate(central_label,color=GOLD));self.finish();self.done()

