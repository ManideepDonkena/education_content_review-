def think(scene):
    scene.until(scene.beat_start+scene.current['speech_end'])
    line=Line([1.25,-2.05,0],[6.15,-2.05,0],color=GOLD,stroke_width=5)
    label=txt('Think it through',26,GOLD).move_to([3.7,-1.55,0])
    scene.add(label);scene.play(Create(line),run_time=8,rate_func=linear)
    scene.remove(label,line)

