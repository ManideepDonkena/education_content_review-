def unit_board():
    g,A,B,C=tri(1,1,center=(-3.25,0,0),scale=2.5,labels=('1 m','1 m','?'))
    top=Line(A+UP*2.5,C,color=MUTED);left=Line(A,A+UP*2.5,color=MUTED)
