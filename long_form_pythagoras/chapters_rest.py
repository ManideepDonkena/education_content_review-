        self.cue('There are four identical triangles',Indicate(tris),self.panel_to(eq(r'4\times\tfrac12ab=2ab',43)))
        central_label=eq('c^2',48,PINK).move_to(inner)
        self.cue('The central square has side c',FadeIn(central_label),self.panel_to(eq(r'\text{pieces}=2ab+c^2',42)))
        self.cue('so the two expressions must be equal',self.panel_to(eq('a^2+2ab+b^2',41),eq('=2ab+c^2',43)))
        self.finish()
        self.begin('19');self.cue('Set those expressions equal',self.panel_to(eq('a^2+2ab+b^2',41),eq('=2ab+c^2',43)))
