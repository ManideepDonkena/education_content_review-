    def construct(self):
        self.chapter(5);outer,tris,inner,side,pts=proof_board()
        self.begin('17');self.cue('Keep the same picture',Create(outer),Create(tris),Create(inner),FadeIn(side))
        self.cue('The outer square has side a plus b',self.panel_to(eq('(a+b)^2',54)))
        self.cue('Multiplying a plus b by itself',self.panel_to(eq('(a+b)(a+b)',43),eq('a^2+ab+ab+b^2',40)))
        self.cue('Together those middle terms',self.panel_to(eq('(a+b)^2',45),eq('=a^2+2ab+b^2',43)))
